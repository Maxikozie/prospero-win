"""Import thunks for an Orbis PRX that takes functions from a sibling
application PRX without the console loader: one C file defining, for each
name, a global function that jumps through a slot, and

  int pw_prx_bind_imports(const void *(*resolve)(void *context, const char *name),
                          void *context);

which fills every slot from RESOLVE (the title passes a look-up in the
exporter's PRXDESC1 table) and returns the number of names it could not
resolve. A thunk called before its slot is filled jumps to address 0.

Functions only: a data object would need its address, not a jump, and the
importer's code reads data through its own GOT, which no thunk can redirect.
The caller lists function names; nothing here can check their type.

Usage: gen_prx_imports.py OUT.c NAME [NAME ...]
"""
import re
import sys

NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def generate(names):
    count = len(names)
    out = ["/* Generated by tools/gen_prx_imports.py; do not edit. */",
           "#include <stddef.h>",
           "",
           f"__attribute__((visibility(\"hidden\"), used)) const void *pw_prx_import_slots[{count}];",
           f"static const char *const pw_prx_import_names[{count}] = {{"]
    out += [f"    \"{name}\"," for name in names]
    out += ["};", ""]
    for index, name in enumerate(names):
        out.append(f"__asm__(\".text\\n.globl {name}\\n.type {name},@function\\n{name}:\\n"
                   f"\\tjmp *pw_prx_import_slots+{8 * index}(%rip)\\n.size {name},.-{name}\\n\");")
    out += ["",
            "int pw_prx_bind_imports(const void *(*resolve)(void *context, const char *name), void *context)",
            "{",
            "    int missing = 0;",
            f"    for (size_t i = 0; i < {count}; i++)",
            "    {",
            "        pw_prx_import_slots[i] = resolve(context, pw_prx_import_names[i]);",
            "        if (!pw_prx_import_slots[i]) missing++;",
            "    }",
            "    return missing;",
            "}",
            ""]
    return "\n".join(out)


def main(argv):
    if len(argv) < 3 or argv[1] in ("-h", "--help"):
        print(__doc__.strip())
        return 0 if len(argv) > 1 and argv[1] in ("-h", "--help") else 1
    names = argv[2:]
    bad = [n for n in names if not NAME.match(n)]
    if bad or len(set(names)) != len(names):
        print(f"gen_prx_imports: invalid or repeated names: {bad or names}", file=sys.stderr)
        return 1
    with open(argv[1], "w") as f:
        f.write(generate(names))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
